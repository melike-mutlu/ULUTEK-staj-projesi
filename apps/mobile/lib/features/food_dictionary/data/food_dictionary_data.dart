  /// Filters terms by search query and category
  static List<FoodTerm> searchTerms({
    required String query,
    FoodDictionaryCategory category = FoodDictionaryCategory.all,
  }) {
    final cleanQuery = query.trim().toLowerCase();

    return allTerms.where((term) {
      // Category filter
      if (category != FoodDictionaryCategory.all && term.category != category) {
        return false;
      }

      // Query filter
      if (cleanQuery.isEmpty) return true;

      final matchesName = term.name.toLowerCase().contains(cleanQuery);
      final matchesCode = term.code != null && term.code!.toLowerCase().contains(cleanQuery);
      final matchesSubCat = term.subCategory.toLowerCase().contains(cleanQuery);
      final matchesDesc = term.description.toLowerCase().contains(cleanQuery);
      final matchesTags = term.tags.any((tag) => tag.toLowerCase().contains(cleanQuery));

      return matchesName || matchesCode || matchesSubCat || matchesDesc || matchesTags;
    }).toList();
  }
